// その経歴の書き分けがあれば返す。高校卒業は元の台本のまま（undefined）
export function rivalVariant(s: GameState, key: string): ReturnType<Variant> | undefined {
  const c = s.player.background
  if (c !== 'circle' && c !== 'salaryman') return undefined
  return V[key]?.[c]?.(s)
}

