// 門出のあと、御堂の相方がどうするか
export function midoPartnerLine(s: GameState): string {
  if (s.flags.mido_warai) return '御堂（照れ）「相方、もう1年やるって。決め手は、僕が舞台で笑ったことだって。……ノートのあれ、成功したらしいよ」'
  if (s.gradRank === 1) return '御堂（照れ）「相方、もう1年やるって。準優勝で十分だって。……十分なわけ、ないのにね」'
  return '御堂（照れ）「相方、もう1年やるって。……優勝したら、言いだしにくいだろうと思ってたけど」'
}

