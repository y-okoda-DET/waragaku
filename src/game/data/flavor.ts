// キーの文から1つ選び、{placeholder} を vars で置き換える。vars にないものはそのまま残す。
export function flavor(key: FlavorKey, rng: Rng, vars?: Record<string, string>): string {
  const line = rng.pick(FLAVOR[key])
  if (!vars) return line
  return line.replace(/\{(\w+)\}/g, (m, k: string) => vars[k] ?? m)
}
